import argparse
import sys
from pathlib import Path

# cookies.py lives at <repo>/src/ieee_tools/cookies.py -> parents[2] is repo root.
PROJECT_ROOT = Path(__file__).resolve().parents[2]

# 专门给 IEEE 下载器使用的 Chromium Profile（由 Playwright 自带的 Chromium 使用）
USER_DATA_DIR = PROJECT_ROOT / ".cache/ieee-chrome-profile"

OUTPUT = PROJECT_ROOT / "config/ieee_cookies.txt"

CHROMIUM_INSTALL_HINT = (
    "未检测到 Playwright 自带的 Chromium 内核。\n"
    "请先执行下面的命令安装 Chromium，再重新运行本脚本：\n\n"
    "    playwright install chromium\n\n"
    "使用 uv 管理环境时，请执行：\n\n"
    "    uv run playwright install chromium\n"
)


def _import_playwright():
    """导入 Playwright（惰性：只在真正导出 Cookie 时才要求已安装）。

    未安装时给出安装指引并退出，避免 import 本模块（如 ieee-tools status）
    被 Playwright 硬依赖拖累。
    """
    try:
        from playwright.sync_api import Error as PlaywrightError
        from playwright.sync_api import sync_playwright
    except ImportError:
        sys.exit(
            "playwright is not installed. Install it with:\n"
            "  pip install playwright\n"
            "  playwright install chromium"
        )
    return sync_playwright, PlaywrightError


def resolve_chromium_executable(playwright) -> Path:
    """返回 Playwright 自带 Chromium 的期望路径。

    新版 Playwright（>=1.49）中 executable_path 是属性，旧版是方法，两种都兼容。
    """
    executable = playwright.chromium.executable_path
    if callable(executable):
        executable = executable()
    return Path(executable)


def ensure_chromium_installed(playwright) -> None:
    """确认 Playwright 自带的 Chromium 内核已下载，否则提示安装并退出。"""
    executable = resolve_chromium_executable(playwright)

    if executable.exists():
        return

    print(f"期望的 Chromium 路径不存在: {executable}", file=sys.stderr)
    print(file=sys.stderr)
    print(CHROMIUM_INSTALL_HINT, file=sys.stderr)
    sys.exit(1)


def write_netscape_cookie_file(cookies, output: Path = OUTPUT):
    output.parent.mkdir(parents=True, exist_ok=True)

    with output.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# Netscape HTTP Cookie File\n")
        f.write("# This file was generated by Playwright.\n\n")

        for cookie in cookies:
            domain = cookie["domain"]

            if cookie.get("httpOnly", False):
                domain = "#HttpOnly_" + domain

            include_subdomains = "TRUE" if cookie["domain"].startswith(".") else "FALSE"

            path = cookie.get("path", "/")

            expires = cookie.get("expires", -1)

            if expires is None or expires < 0:
                expires = 0
            else:
                expires = int(expires)

            secure = "TRUE" if cookie.get("secure", False) else "FALSE"

            name = cookie["name"]
            value = cookie["value"]

            value = value.replace("\t", "").replace("\r", "").replace("\n", "")

            f.write(
                f"{domain}\t"
                f"{include_subdomains}\t"
                f"{path}\t"
                f"{secure}\t"
                f"{expires}\t"
                f"{name}\t"
                f"{value}\n"
            )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="ieee-tools export_cookies",
        description=(
            "Open Chromium to log in to IEEE Xplore and export a Netscape "
            "cookies.txt file. Login is performed manually in the window."
        ),
    )
    parser.add_argument(
        "--output", type=Path, default=OUTPUT,
        help="Netscape cookie output path (default: config/ieee_cookies.txt)",
    )
    parser.add_argument(
        "--headless", action="store_true",
        help="Run Chromium headless (only useful if login is already cached)",
    )
    return parser


def main(argv: list[str] | None = None):
    parser = build_parser()
    args = parser.parse_args(argv)

    sync_playwright, PlaywrightError = _import_playwright()
    with sync_playwright() as p:
        ensure_chromium_installed(p)

        USER_DATA_DIR.mkdir(parents=True, exist_ok=True)

        try:
            # 不传 executable_path，使用 Playwright 自带的 Chromium
            context = p.chromium.launch_persistent_context(
                user_data_dir=str(USER_DATA_DIR),
                headless=args.headless,
                args=[
                    "--disable-gpu",
                ],
            )
        except PlaywrightError as exc:
            # 兜底：文件检查通过但启动时仍提示内核缺失（如下载不完整）
            if "Executable doesn't exist" in exc.message or "playwright install" in exc.message:
                print(f"Chromium 启动失败：{exc.message}", file=sys.stderr)
                print(CHROMIUM_INSTALL_HINT, file=sys.stderr)
                sys.exit(1)
            raise

        page = context.pages[0] if context.pages else context.new_page()

        page.goto(
            "https://ieeexplore.ieee.org/",
            wait_until="domcontentloaded",
        )

        print()
        print("IEEE Chromium Profile:")
        print(USER_DATA_DIR)
        print()
        print("请在打开的 Chromium 中完成 IEEE Xplore 登录。")
        print("确认能够访问你有权限下载的论文后，再回终端。")
        print()

        input("登录完成后按 Enter 导出 Cookie...")

        cookies = context.cookies()

        ieee_cookies = [
            cookie for cookie in cookies if cookie["domain"].endswith("ieee.org")
        ]

        write_netscape_cookie_file(ieee_cookies, args.output)

        print()
        print(f"读取 Cookie: {len(cookies)}")
        print(f"IEEE Cookie: {len(ieee_cookies)}")
        print(f"输出文件: {args.output.resolve()}")

        context.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
